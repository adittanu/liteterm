-- LiteTerm cloud sync, end-to-end encrypted.
--
-- The server stores only what the app already encrypted. It never sees the
-- master password, the vault key, or any host, credential, key or note in
-- plaintext. What it does see: the account email, how many items a user has,
-- their sizes, and when they change.
--
-- Apply once: Supabase dashboard → SQL Editor → New query → paste → Run.

-- ---------------------------------------------------------------------------
-- vaults: one row per user, holding what a new device needs to unlock.
-- ---------------------------------------------------------------------------
create table public.vaults (
  user_id               uuid primary key default auth.uid()
                        references auth.users (id) on delete cascade,
  -- Changes when a vault is reset (deleted and set up again). A device that
  -- sees a different vault_id than it synced with starts over from rev 0.
  vault_id              uuid not null default gen_random_uuid(),
  -- How the master password becomes the key-encryption key, e.g.
  -- {"alg":"argon2id","m":65536,"t":3,"p":1,"salt":"<base64>"}
  kdf                   jsonb not null,
  -- The random vault key, encrypted with the master-password key
  wrapped_key           text not null,
  -- The same vault key, encrypted with the recovery key shown once at setup
  wrapped_key_recovery  text not null,
  -- Per-user change counter; each pushed change takes the next value
  rev                   bigint not null default 0,
  created_at            timestamptz not null default now()
);

-- ---------------------------------------------------------------------------
-- vault_items: one row per synced record (host, group, credential, snippet,
-- note, port forward, known host). Its kind lives inside the ciphertext.
-- ---------------------------------------------------------------------------
create table public.vault_items (
  user_id      uuid not null references public.vaults (user_id) on delete cascade,
  -- The record's sync_id, generated by the app
  id           uuid not null,
  -- base64(nonce || ciphertext); null once the record is deleted
  data         text,
  deleted      boolean not null default false,
  -- When the edit was made (ms since epoch, device clock). On a conflict the
  -- newer edit wins.
  modified_at  bigint not null,
  -- Server order of changes for this user; a device pulls "rev > last seen"
  rev          bigint not null,
  primary key (user_id, id),
  constraint data_present check (deleted or data is not null),
  constraint data_size check (octet_length(data) <= 4 * 1024 * 1024)
);

create index vault_items_user_rev on public.vault_items (user_id, rev);

-- ---------------------------------------------------------------------------
-- push_items: the only way to write vault_items.
--
-- items: [{"id": uuid, "data": text|null, "deleted": bool, "modified_at": ms}]
-- Returns the user's rev after the push. An item older than the stored copy
-- is skipped (last write wins).
-- ---------------------------------------------------------------------------
create function public.push_items(items jsonb)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  uid     uuid := auth.uid();
  cur     bigint;
  item    jsonb;
  is_del  boolean;
begin
  if uid is null then
    raise exception 'not signed in' using errcode = '28000';
  end if;
  if jsonb_typeof(items) is distinct from 'array' or jsonb_array_length(items) > 500 then
    raise exception 'items must be an array of at most 500 entries' using errcode = '22023';
  end if;

  -- Hold the vault row lock until commit, so one user's pushes run one at a
  -- time: revs commit in order and a pull can never skip over a change.
  select v.rev into cur from public.vaults v where v.user_id = uid for update;
  if not found then
    raise exception 'vault not set up' using errcode = 'P0002';
  end if;

  for item in select * from jsonb_array_elements(items) loop
    is_del := coalesce((item->>'deleted')::boolean, false);

    insert into public.vault_items as v (user_id, id, data, deleted, modified_at, rev)
    values (
      uid,
      (item->>'id')::uuid,
      case when is_del then null else item->>'data' end,
      is_del,
      (item->>'modified_at')::bigint,
      cur + 1
    )
    on conflict (user_id, id) do update
      set data        = excluded.data,
          deleted     = excluded.deleted,
          modified_at = excluded.modified_at,
          rev         = excluded.rev
      where v.modified_at < excluded.modified_at;

    if found then
      cur := cur + 1;
    end if;
  end loop;

  update public.vaults set rev = cur where user_id = uid;
  return cur;
end;
$$;

-- ---------------------------------------------------------------------------
-- Access: each user reaches only their own rows. Items are read directly
-- (GET /rest/v1/vault_items?rev=gt.N&order=rev) and written only through
-- push_items. Deleting the vault row resets the vault and all its items.
-- ---------------------------------------------------------------------------
alter table public.vaults      enable row level security;
alter table public.vault_items enable row level security;

create policy "own vault: read" on public.vaults
  for select to authenticated using (user_id = (select auth.uid()));
create policy "own vault: create" on public.vaults
  for insert to authenticated with check (user_id = (select auth.uid()));
create policy "own vault: update" on public.vaults
  for update to authenticated
  using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));
create policy "own vault: reset" on public.vaults
  for delete to authenticated using (user_id = (select auth.uid()));

create policy "own items: read" on public.vault_items
  for select to authenticated using (user_id = (select auth.uid()));

revoke all on public.vaults, public.vault_items from anon, authenticated;
grant select, delete on public.vaults to authenticated;
-- The app sets these; vault_id and rev are the server's
grant insert (user_id, kdf, wrapped_key, wrapped_key_recovery) on public.vaults to authenticated;
grant update (kdf, wrapped_key, wrapped_key_recovery) on public.vaults to authenticated;
grant select on public.vault_items to authenticated;

revoke all on function public.push_items(jsonb) from public, anon;
grant execute on function public.push_items(jsonb) to authenticated;
